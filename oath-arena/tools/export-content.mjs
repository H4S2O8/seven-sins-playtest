import fs from 'node:fs/promises';
import {UNITS,CARDS,RULES,PLEDGES,EFFECTS,KEYWORDS,CONTENT} from '../content.js';
const parts=['# 逆誓竞技场 · 完整内容表\n\n由游戏实际数据导出。兵种30、效果牌50、规则50、承诺50。\n\n规则采用25指标的正反方向；效果牌采用26底层效果配对。所有对象ID稳定，可替换美术及调整数值。'];
parts.push('## 兵种');
for(const u of UNITS)parts.push(`### ${u.id} · ${u.name}\n\n人口 ${u.pop}；生命 ${u.hp}；伤害 ${u.atk}；射程 ${u.range}；间隔 ${u.interval}秒；移速 ${u.speed}。\n\n${u.tags.map(t=>KEYWORDS[t]).join('\n\n')}\n\n> ${u.flavor}`);
