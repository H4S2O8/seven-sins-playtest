parts.push('## 共用规则');for(const r of RULES)parts.push(`### ${r.id} · ${r.name}\n\n${r.description}\n\n关联：${r.counter}。指标：${r.metric}。`);
parts.push('## 公开承诺');for(const p of PLEDGES)parts.push(`### ${p.id} · ${p.name}\n\n${p.description}`);
await fs.writeFile(new URL('../CATALOG.md',import.meta.url),parts.join('\n\n')+'\n');
await fs.writeFile(new URL('../catalog.json',import.meta.url),JSON.stringify({...CONTENT,effects:EFFECTS,keywords:KEYWORDS},null,2));
console.log('Exported 180 entries to CATALOG.md and catalog.json');
