// 由 ../词库.tsv（旧100词）+ 新增词生成 data/words.tsv。列：id 词 类别 稀有度 价格 已实现 权重 含义
import {readFileSync,writeFileSync} from 'node:fs';
const old=readFileSync(new URL('../词库.tsv',import.meta.url),'utf8').trim().split(/\r?\n/).slice(1).map(l=>l.split('\t'));
const AMP=new Set(['027','029','033','072','012','059','069','070','066','071','073','103','109','090','092','106','053','073']);
const EFF=new Set(['001','002','003','005','006','007','008','009','010','011','034','038','039','040','041','042','043','044','045','046','047','048','049','050','051','052','090','091','092','101','102','104','105','106','107','054','056']);
const price=id=>AMP.has(id)?4:EFF.has(id)?1:0;
const common=new Set(['001','002','003','004','005','009','010','013','014','015','016','019','020','026','034','038','039','041','064','065','074','075']);
const medium=new Set(['011','027','031','059','062','069','070','104','017']);
const NOIMPL=new Set([]);
const add=[
['101','延后','动作','进阶','把一方已宣告技能的起点向后推若干秒（填入秒数）；推出20秒则落空。须在目标技能开始前生效。'],
['102','提前','动作','进阶','把一方已宣告技能的起点向前推若干秒（填入秒数），不早于其起手时间。'],
['103','打断','动作','进阶','取消对方已宣告技能中尚未发生的全部部分；起效时间若晚于对方起点，只取消此后的部分。'],
['104','换位','动作','基础','让己方两名随从交换公开位置；不能与对方换位。'],
['105','护盾','状态','进阶','状态：吸收所填数值的伤害，吸收完毕即消失。'],
['106','易伤','状态','进阶','状态：受到的伤害增加50%（向上取整）。'],
['107','沉默','状态','进阶','状态：不能发动新技能；已在时间轴上的技能不受影响。'],
];
const DROP=new Set(['053','054','061','051']); // 053立即 054之前 061下轮 051复出：时间由宣告时的起效时间决定；每轮干净，不跨轮 // 立即、之前：时间由宣告时的“起效时间”决定，不做成词
const rows=[...old.map(([id,w,c,r,d])=>[id,w,c,r,d]),...add].filter(r=>!DROP.has(r[0]));
const out=['id\t词\t类别\t稀有度\t价格\t已实现\t权重\t含义'];
for(const [id,w,c,r,d] of rows){
  out.push([id,w,c,r,price(id),NOIMPL.has(id)?0:1,common.has(id)?3:medium.has(id)?2:1,d].join('\t'));
}
writeFileSync(new URL('./data/words.tsv',import.meta.url),out.join('\n')+'\n');
